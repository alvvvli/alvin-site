  function project(lon, lat) {
    const x = ((wrapLon(lon - view.centerLon) + 180) / 360) * WORLD.width;
    const y = ((90 - (lat - view.centerLat)) / 180) * WORLD.height;
    return {
      x: (x - WORLD.width / 2) * view.zoom + WORLD.width / 2,
      y: (y - WORLD.height / 2) * view.zoom + WORLD.height / 2,
    };
  }
  function unproject(x, y) {
    const ux = (x - WORLD.width / 2) / view.zoom + WORLD.width / 2;
    const uy = (y - WORLD.height / 2) / view.zoom + WORLD.height / 2;
    return {
      lon: wrapLon((ux / WORLD.width) * 360 - 180 + view.centerLon),
      lat: clamp(90 - (uy / WORLD.height) * 180 + view.centerLat, -85, 85),
    };
  }
