  function resolvePackage(pkg, alert) {
    const members = pkg.memberIds
      .map((id) => state.aircraft.find((a) => a.id === id))
      .filter(Boolean);
    const readiness = members.reduce((s, a) => s + a.readiness, 0) / Math.max(1, members.length);
    const timeBonus = Math.max(0, alert.deadline - alert.age);
    const successChance = clamp(
      0.68 + readiness / 500 - alert.severity * 0.035 + timeBonus / 500,
      0.58,
      0.97,
    );
    const success = rand() < successChance;
    if (success) {
      const points = Math.round(alert.baseScore + timeBonus * 4 + readiness);
      state.score += points;
      alert.status = "RESOLVED";
      log(`${pkg.id} MISSION COMPLETE · ${alert.id} · +${points} SCORE`, "success");
      addEffect(alert.lon, alert.lat, COLORS.green);
    } else {
      state.score = Math.max(0, state.score - 240);
      alert.status = "FAILED";
      log(`${pkg.id} MISSION DEGRADED · ${alert.id} · COMMAND PENALTY`, "danger");
      addEffect(alert.lon, alert.lat, COLORS.alert);
    }
    releasePackage(pkg, success);
    setTimeout(() => {
      state.alerts = state.alerts.filter((a) => a.id !== alert.id);
      state.packages = state.packages.filter((p) => p.id !== pkg.id);
      if (state.selected?.id === alert.id) state.selected = null;
      updateUi();
    }, 3200);
    updateUi();
  }
