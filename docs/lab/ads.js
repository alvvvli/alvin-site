  function dispatchPackage(alertArg = null, quiet = false) {
    const alert = alertArg || (selectedObject()?.kind === "alert" ? selectedObject() : null);
    if (!alert) {
      toast("Select an alert zone first");
      return null;
    }
    if (alert.status === "RESOLVED") {
      toast("Alert is already resolved");
      return null;
    }
    if (alert.packageId) {
      toast(`${alert.id} already has a task package`);
      return state.packages.find((p) => p.id === alert.packageId) || null;
    }
    const members = [];
    for (const [role, count] of Object.entries(alert.need)) {
      members.push(...nearestAvailable(role, alert, count));
    }
    const required = Object.values(alert.need).reduce((a, b) => a + b, 0);
    if (members.length < required) {
      if (!quiet) toast("Insufficient unassigned aircraft for package");
      log(
        `PACKAGE BUILD FAILED · ${alert.id} · ${members.length}/${required} AIRCRAFT AVAILABLE`,
        "warning",
      );
      return null;
    }
    const packageObj = {
      id: `PKG-${String(state.nextPackageId++).padStart(3, "0")}`,
      kind: "package",
      alertId: alert.id,
      memberIds: members.map((a) => a.id),
      status: "ENROUTE",
      createdAt: state.elapsed,
      arrived: new Set(),
      resolveTimer: 0,
    };
    state.packages.push(packageObj);
    alert.packageId = packageObj.id;
    alert.status = "PACKAGE ENROUTE";
    for (const aircraft of members) {
      aircraft.packageId = packageObj.id;
      aircraft.alertId = alert.id;
      aircraft.destLon = alert.lon + (rand() - 0.5) * 1.8;
      aircraft.destLat = alert.lat + (rand() - 0.5) * 1.2;
      aircraft.status = "TASKED";
      aircraft.priority = true;
    }
    state.score = Math.max(0, state.score - 25);
    log(`${packageObj.id} DISPATCHED · ${alert.id} · ${members.length} AIRCRAFT`, "success");
    if (!quiet) toast(`${packageObj.id} airborne`);
    updateUi();
    return packageObj;
  }

