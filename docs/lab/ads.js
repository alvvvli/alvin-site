  function updateAircraft(a, dt) {
    const dx = lonDelta(a.lon, a.destLon) * Math.cos((((a.lat + a.destLat) / 2) * Math.PI) / 180);
    const dy = a.destLat - a.lat;
    const d = Math.hypot(dx, dy);
    if (d < 0.7) {
      if (a.packageId) {
        const pkg = state.packages.find((p) => p.id === a.packageId);
        if (pkg) {
          pkg.arrived.add(a.id);
          a.status = "ON STATION";
          a.speed = 0.08;
        } else {
          a.packageId = null;
        }
      } else {
        const next = choice(hubs.filter((h) => h.id !== a.destinationId));
        a.originId = a.destinationId;
        a.destinationId = next.id;
        a.destLon = next.lon + (rand() - 0.5) * 4;
        a.destLat = next.lat + (rand() - 0.5) * 2.5;
        a.status = rand() < 0.5 ? "PATROL" : "TRANSIT";
        a.speed = Math.max(a.speed, 0.32);
        a.fuel = Math.round(75 + rand() * 24);
      }
    } else {
      const step = a.speed * dt;
      const lonStep = ((dx / d) * step) / Math.max(0.3, Math.cos((a.lat * Math.PI) / 180));
      a.lon = wrapLon(a.lon + lonStep);
      a.lat = clamp(a.lat + (dy / d) * step, -82, 82);
      a.fuel = Math.max(0, a.fuel - dt * 0.035);
      if (a.fuel < 22 && !a.packageId) {
        const hub = nearestHub(a);
        a.destLon = hub.lon;
        a.destLat = hub.lat;
        a.destinationId = hub.id;
        a.status = "LOW FUEL RTB";
      }
    }
    a.trail.push({ lon: a.lon, lat: a.lat });
    if (a.trail.length > 12) a.trail.shift();
  }

  function update(dt) {
    state.elapsed += dt;
    state.autoAlertTimer -= dt;
    if (state.autoAlertTimer <= 0 && state.alerts.length < 5) {
      createAlert(false);
      state.autoAlertTimer = 20 + rand() * 22;
    }
    for (const a of state.aircraft) updateAircraft(a, dt);
    for (const alert of state.alerts) {
      alert.age += dt;
      alert.pulse += dt * 2.4;
      if (alert.status !== "RESOLVED" && alert.status !== "FAILED" && alert.age > alert.deadline) {
        alert.status = "OVERDUE";
        if (Math.floor(alert.age) % 8 === 0) state.score = Math.max(0, state.score - 1);
      }
    }
    for (const pkg of state.packages) {
      if (pkg.status !== "ENROUTE") continue;
      const alert = state.alerts.find((a) => a.id === pkg.alertId);
      if (!alert) continue;
      const required = pkg.memberIds.length;
      if (pkg.arrived.size >= Math.max(2, Math.ceil(required * 0.72))) {
        pkg.resolveTimer += dt;
        if (pkg.resolveTimer > 2.4) {
          pkg.status = "RESOLVING";
          resolvePackage(pkg, alert);
        }
      }
    }
    for (const e of state.effects) {
      e.radius += dt * 22;
      e.alpha -= dt * 0.55;
    }
    state.effects = state.effects.filter((e) => e.alpha > 0);
    updateUi(false);
  }

